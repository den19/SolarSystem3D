def assert_limits(events: list[dict] | None = None) -> None:
    """Raise AssertionError if any event exceeds RuStore console limits."""
    for ev in events if events is not None else EVENTS:
        tid = ev["id"]
        title, short, desc = ev["title"], ev["short"], ev["description"]
        assert len(title) <= TITLE_MAX, (
            f"#{tid} title {len(title)} > {TITLE_MAX}: {title!r}"
        )
        assert len(short) <= SHORT_MAX, (
            f"#{tid} short {len(short)} > {SHORT_MAX}: {short!r}"
        )
        assert len(desc) <= DESC_MAX, (
            f"#{tid} description {len(desc)} > {DESC_MAX}"
        )
        assert ev["text_color"] in ("white", "black"), tid
        assert ev["fill_hex"].startswith("#") and len(ev["fill_hex"]) == 7, tid
        assert 2 <= len(ev["companions"]) <= 3, tid
        words = ev["cover_brief"]["safe_zone_words"].split()
        assert 1 <= len(words) <= 3, tid
        assert ev["priority"] in ("A", "B", "C"), tid


